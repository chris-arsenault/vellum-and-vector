use super::kinds::Kind;
pub fn kind(system: &str, rule: &str) -> Option<Kind> {
    use Kind::*;
    Some(match (system, rule) {
        ("fire", "core") => FireCore,
        ("fire", "vein") => ThermalVein,
        ("fire", "spring") | ("greenwood", "wellspring") => Spring,
        ("fire", "vent") => Vent,
        ("fire", "basalt") => BasaltFlat,
        ("fire", "scar") => BasaltScar,
        ("fire", "crater") => Crater,
        ("fire", "fan") => EjectaFan,
        ("fire", "placer") => Placer,
        ("fire", "deviation") => CompassDeviation,
        ("fire", "halo") => ThawedHalo,
        ("aurora", "field") => AuroraField,
        ("aurora", "well") => LightWell,
        ("aurora", "prism") => FrostPrism,
        ("aurora", "melt") => MeltLine,
        ("pressure", "locus") => PressureLocus,
        ("pressure", "crush") => CrushZone,
        ("pressure", "front") => UpwellingFront,
        ("pressure", "wake") => AncientWake,
        ("pressure", "lattice") => InterferenceLattice,
        ("pressure", "rogue") => RogueWaveImpact,
        ("greenwood", "stand") => GreenwoodStand,
        ("greenwood", "oasis") => Oasis,
        ("greenwood", "verdant") => VerdantGround,
        ("greenwood", "sinkhole") => SinkholeField,
        ("salt", "ground") => KillingGround,
        ("salt", "pan") => SaltPan,
        ("salt", "flat") => GlassFlat,
        ("salt", "dust") => SaltDust,
        ("veil", "tear") => Tear,
        ("veil", "wild") => WildZone,
        ("veil", "door") => Door,
        ("hallowed", "ring") => WardRing,
        ("hallowed", "line") => WardLine,
        _ => return None,
    })
}
