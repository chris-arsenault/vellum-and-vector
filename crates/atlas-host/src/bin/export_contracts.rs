//! Build-time generation; does not run when a map opens.
use std::{fs, path::PathBuf};

fn main() -> std::io::Result<()> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let header = "// Generated by cargo run -p atlas-host --bin export_contracts. Do not edit.\n\n";
    let map = root.join("packages/map/src/generated.ts");
    let generation = root.join("packages/atlas-context/src/generated.ts");
    fs::create_dir_all(map.parent().expect("map output parent"))?;
    fs::create_dir_all(generation.parent().expect("generation output parent"))?;
    let core = atlas_map::declarations();
    let editing = atlas_map::editing_declarations();
    // Each file imports the other's names it uses; type-only imports may go both ways.
    fs::write(
        &map,
        format!(
            "{header}{}{core}\n",
            imports(&editing, &core, "./generatedEditing")
        ),
    )?;
    fs::write(
        map.with_file_name("generatedEditing.ts"),
        format!(
            "{header}{}{editing}\n",
            imports(&core, &editing, "./generated")
        ),
    )?;
    // The structure-map vocabulary (level names, connection kinds and reach, shell settings)
    // is declared once in Rust and served to the view as data.
    fs::write(
        map.with_file_name("generatedStructure.ts"),
        format!(
            "{header}export const structureVocabulary = {} as const;\n",
            atlas_map::structure::VOCABULARY.trim()
        ),
    )?;
    // Authored-map calls (ADR 0019): the host's call types and the terrain shapes they carry.
    let authoring_cfg = ts_rs::Config::default();
    fs::write(
        map.with_file_name("generatedAuthoring.ts"),
        format!(
            "{header}{}\n",
            [
                <atlas_host::authored_maps::AuthoredProfile as ts_rs::TS>::decl(&authoring_cfg),
                <atlas_host::authored_maps::NewMapRequest as ts_rs::TS>::decl(&authoring_cfg),
                <atlas_host::authored_terrain::TerrainEdit as ts_rs::TS>::decl(&authoring_cfg),
                <atlas_host::authored_terrain::TerrainOutcome as ts_rs::TS>::decl(&authoring_cfg),
                <atlas_generation::publication::authored::Stroke as ts_rs::TS>::decl(
                    &authoring_cfg
                ),
                <atlas_generation::publication::authored::BrushMode as ts_rs::TS>::decl(
                    &authoring_cfg
                ),
                <atlas_generation::publication::authored::HeightLine as ts_rs::TS>::decl(
                    &authoring_cfg
                ),
                <atlas_generation::publication::authored::HeightArea as ts_rs::TS>::decl(
                    &authoring_cfg
                ),
                <atlas_generation::publication::authored::HeightPeak as ts_rs::TS>::decl(
                    &authoring_cfg
                ),
                <atlas_generation::publication::authored::Rect as ts_rs::TS>::decl(&authoring_cfg),
            ]
            .map(|declaration| format!("export {declaration}"))
            .join("\n")
        ),
    )?;
    fs::write(
        generation,
        format!(
            "{header}import type {{ MapRef, RegionSelection, RasterBand, Bounds, Geometry, RealScaleKind }} from '@atlas/map';\n\n{}\n",
            atlas_generation::declarations()
        ),
    )?;
    Ok(())
}
/// The names declared in `from` that `user` mentions, imported from module `path`.
fn imports(from: &str, user: &str, path: &str) -> String {
    let words = user
        .split(|c: char| !(c.is_alphanumeric() || c == '_'))
        .collect::<std::collections::BTreeSet<_>>();
    let used = from
        .split("export type ")
        .skip(1)
        .filter_map(|rest| {
            rest.split(|c: char| !(c.is_alphanumeric() || c == '_'))
                .next()
        })
        .filter(|name| words.contains(name))
        .collect::<Vec<_>>();
    if used.is_empty() {
        return String::new();
    }
    format!("import type {{ {} }} from \"{path}\";\n\n", used.join(", "))
}
