//! Build-time generation; does not run when a map opens.
use std::{fs, path::PathBuf};

fn main() -> std::io::Result<()> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let header = "// Generated by cargo run -p atlas-host --bin export_contracts. Do not edit.\n\n";
    let map = root.join("packages/map/src/generated.ts");
    let generation = root.join("packages/atlas-context/src/generated.ts");
    fs::create_dir_all(map.parent().expect("map output parent"))?;
    fs::create_dir_all(generation.parent().expect("generation output parent"))?;
    fs::write(map, format!("{header}{}\n", atlas_map::declarations()))?;
    fs::write(
        generation,
        format!(
            "{header}import type {{ MapRef, RegionSelection, RasterBand, Bounds, Geometry }} from '@atlas/map';\n\n{}\n",
            atlas_generation::declarations()
        ),
    )?;
    Ok(())
}
